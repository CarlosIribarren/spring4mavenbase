package oiasso.systems.spring4mavenbasecorelib.beans;

public class Datos {

	private String[] datosChk;
	private String datosRad;
	private String datosSel;
	private String datosTextarea;

	public String getDatosRad() {
		return datosRad;
	}

	public void setDatosRad(String datosRad) {
		this.datosRad = datosRad;
	}

	public String getDatosSel() {
		return datosSel;
	}

	public void setDatosSel(String datosSel) {
		this.datosSel = datosSel;
	}

	public String[] getDatosChk() {
		return datosChk;
	}

	public void setDatosChk(String[] datosChk) {
		this.datosChk = datosChk;
	}

	public String getDatosTextarea() {
		return datosTextarea;
	}

	public void setDatosTextarea(String datosTextarea) {
		this.datosTextarea = datosTextarea;
	}	
}
